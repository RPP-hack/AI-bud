"""Normalize common Russian onboarding terms and English tool names for FTS5."""

import re

_PHRASES = (
    (r"\b(?:перв\w* недел\w*|недел\w* 1)\b", "week1 неделя"),
    (r"\b(?:втор\w* недел\w*|недел\w* 2)\b", "week2 неделя"),
    (r"\b(?:pull[ -]?requests?|пулл?[ -]?реквест\w*)\b", "pr"),
    (r"\b(?:code[ -]?review|код[ -]?ревью)\b", "ревью"),
    (r"\bчек[ -]?лист\w*\b", "чеклист"),
    (r"\b(?:посмотреть|проверить) (?:мой |мои )?(?:код|изменения)\b", "ревью"),
    (r"\bci\s*/\s*cd\b", "ci"),
)
_ALIASES = {
    "jira": ("джир",), "confluence": ("конфлю", "конфлу"),
    "bitbucket": ("битбакет",), "pr": ("пулреквест", "пуллреквест"),
    "ревью": ("ревью", "ревь", "реценз", "review"),
    "репозиторий": ("репозитор", "репозитар", "репозу", "репу"),
    "клонировать": ("скача", "склонир", "клонир", "clone"),
    "доступ": ("доступ", "попасть", "правам", "права", "право"),
    "заявка": ("заявк", "заявок"), "задача": ("задач",),
    "сборка": ("сборк", "сборок", "билд", "build"),
    "ошибка": ("ошибк",), "фича": ("фич",), "проверка": ("провер",),
    "backend": ("бэкенд", "бекенд", "бэкендер", "backend"),
    "отправка": ("отправ",), "ветка": ("ветк", "веток",),
    "пайплайн": ("пайплайн", "pipeline"), "падение": ("пада", "упал", "упав", "паден"),
    "окружение": ("окружен", "стенд"), "ноутбук": ("ноут", "лэптоп"),
    "неделя": ("недел",), "настроить": ("настро",), "чеклист": ("чеклист",),
    "проект": ("проект",), "наставник": ("наставник", "ментор"),
}
_STOP = set("""
а без бы был была в во вы где да для до его ее если есть еще же за зачем и из или им их
к как какая какие какой каком какую когда кого кому которая которые куда ли мне могу может
мои мой моя мы на над надо нас наша нашей не него нет но нужно о об он она от по под после
почему при про с сам со так там то у уже чем через что чтобы это эту я у меня мне мой
кто должен заняться нам сделать делать получить получаю найти посмотреть пожалуйста подскажите подскажи
позвать звать добавить добавлять попросить открыть открывается
первый первую первого первом первой новый стажер стажера стажеру
""".split())


def search_terms(text: str) -> list[str]:
    text = text.casefold().replace("ё", "е")
    for pattern, replacement in _PHRASES:
        text = re.sub(pattern, replacement, text)
    terms = []
    for word in re.findall(r"[^\W_]+", text):
        if word in _STOP or len(word) == 1:
            continue
        for term, prefixes in _ALIASES.items():
            if word.startswith(prefixes):
                word = term
                break
        terms.append(word)
    return terms
